"""Build app/data/thesaurus.json: similar words, grouped by meaning, for the word picker.

Build-time only (nltk + wordfreq); the engine reads the JSON with the standard
library:

    python python-engine/tools/build_thesaurus.py

Only the picker uses this (click any word in the result): the user chooses a
word in context, so it can be broader than the rule engine's hand-written
groups, which it never feeds. For each common word, up to --senses WordNet
senses (most frequent first) are kept, each with a short gloss and up to
--per-sense synonyms. Filters:

* the word and each synonym must be common (wordfreq Zipf >= --min-zipf);
* no AI-sounding words (config.AVOID_WORDS), slang (lexicon.CASUAL), or
  words build_lexicon.py excludes; nothing from its BAD_PAIRS;
* no synonym that is just another form of the word ("run" -> "running").

Format: {word: [[pos, gloss, [synonym, ...]], ...]} with pos one of n v a r.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ENGINE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ENGINE))
sys.path.insert(0, str(ENGINE / "tools"))

from build_lexicon import BAD_PAIRS, EXCLUDE  # noqa: E402

from app.core import lexicon as lx  # noqa: E402
from app.core.config import AVOID_WORDS  # noqa: E402

OUT = ENGINE / "app" / "data" / "thesaurus.json"
_POS = {"n": "n", "v": "v", "a": "a", "s": "a", "r": "r"}
_BLOCK = EXCLUDE | AVOID_WORDS | set(lx.CASUAL) | {"nigger", "bitch", "bastard", "whore", "slut", "fuck", "shit"}


def _gloss(definition: str) -> str:
    text = definition.split(";")[0].strip()
    return text if len(text) <= 48 else text[:45].rsplit(" ", 1)[0] + "…"


def build(min_zipf: float, senses: int, per_sense: int) -> dict[str, list]:
    from nltk.corpus import wordnet as wn
    from wordfreq import zipf_frequency

    zipf = {}

    def common(w: str, floor: float) -> bool:
        if w not in zipf:
            zipf[w] = zipf_frequency(w, "en")
        return zipf[w] >= floor

    words = {
        lemma.name()
        for synset in wn.all_synsets()
        for lemma in synset.lemmas()
        if lemma.name().isalpha() and lemma.name().islower()
    }
    out: dict[str, list] = {}
    for word in sorted(words):
        if word in _BLOCK or not common(word, min_zipf):
            continue
        groups: list = []
        seen: set[str] = {word}
        for synset in wn.synsets(word)[: senses * 3]:
            if word not in (lemma.name() for lemma in synset.lemmas()):
                continue  # WordNet maps "showing" to "show"; the engine inflects base forms itself
            syns = []
            for lemma in synset.lemmas():
                cand = lemma.name().replace("_", " ")
                if cand in seen or cand in _BLOCK or (word, cand) in BAD_PAIRS:
                    continue
                if not all(part.isalpha() for part in cand.split()) or len(cand.split()) > 2 or cand[0].isupper():
                    continue
                if cand.startswith(word[:4]) and len(word) > 4:  # another form of the word
                    continue
                if not common(cand, min_zipf + (0.5 if " " not in cand else 0)):
                    continue
                syns.append(cand)
                seen.add(cand)
            if syns:
                groups.append([_POS[synset.pos()], _gloss(synset.definition()), syns[:per_sense]])
            if len(groups) == senses:
                break
        if groups:
            out[word] = groups
    return out


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--min-zipf", type=float, default=3.0)
    p.add_argument("--senses", type=int, default=4)
    p.add_argument("--per-sense", type=int, default=6)
    p.add_argument("--out", type=Path, default=OUT)
    args = p.parse_args()
    data = build(args.min_zipf, args.senses, args.per_sense)
    about = "Generated by tools/build_thesaurus.py from WordNet (WordNet license) and wordfreq. Do not edit."
    args.out.write_text(
        json.dumps({"_about": about, "words": data}, ensure_ascii=False, separators=(",", ":")) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {args.out} ({len(data)} words)")


if __name__ == "__main__":
    main()
