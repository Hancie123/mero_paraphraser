"""Build app/data/ppdb_phrases.json from a local PPDB 2.0 file (CC-BY 3.0).

Build-time only. PPDB is not downloaded here: its original host
(nlpgrid.seas.upenn.edu / paraphrase.org) no longer serves the files, so pass
a copy you have, e.g. the English S packs:

    python python-engine/tools/build_ppdb.py ppdb-2.0-s-phrasal.gz ppdb-2.0-s-o2m.gz

Each PPDB line is

    [LHS] ||| phrase ||| paraphrase ||| features ||| alignment ||| entailment

Kept, in the same spirit as build_lexicon.py's WordNet filters:

* PPDB2Score >= --min-score and entailment "Equivalence" (no hypernyms,
  no "ForwardEntailment" that drops detail, no "Exclusion" opposites);
* 1-4 words a side, letters and apostrophes only, both sides different;
* no hedge, negation or reporting word changes (lexicon.FROZEN), and
  nothing from config.AVOID_WORDS;
* lines with [NN,1]-style slots are kept separately as ``patterns`` when
  both sides use the same slots ("the [NN,1] of [NP,2]" <-> "[NP,2] 's [NN,1]").

Output: {"phrases": {phrase: [[paraphrase, score], ...]}, "patterns": [[lhs, src, dst, score], ...]},
best first. Nothing in the engine reads it yet; review the output before wiring
it into the phrase tables.
"""

from __future__ import annotations

import argparse
import gzip
import json
import re
import sys
from collections.abc import Iterator
from pathlib import Path

ENGINE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ENGINE))

from app.core import lexicon as lx  # noqa: E402
from app.core.config import AVOID_WORDS  # noqa: E402

OUT = ENGINE / "app" / "data" / "ppdb_phrases.json"
_WORDS = re.compile(r"[a-z]+(?:'[a-z]+)?(?: [a-z]+(?:'[a-z]+)?){0,3}")
_SLOT = re.compile(r"\[[A-Z$.,:/\\\-]+,\d\]")
_SCORE = re.compile(r"(?:^| )PPDB2Score=([-\d.e]+)")


def _lines(path: Path) -> Iterator[str]:
    opener = gzip.open if path.suffix == ".gz" else open
    with opener(path, "rt", encoding="utf-8", errors="replace") as f:
        yield from f


def _safe(phrase: str) -> bool:
    words = phrase.split()
    return not any(w in AVOID_WORDS for w in words) and not lx.is_frozen(phrase)


def parse(lines: Iterator[str], min_score: float) -> tuple[dict[str, list], list[list]]:
    phrases: dict[str, dict[str, float]] = {}
    patterns: dict[tuple[str, str, str], float] = {}
    for line in lines:
        parts = [p.strip() for p in line.split("|||")]
        if len(parts) < 6 or parts[5] != "Equivalence":
            continue
        lhs, src, dst, feats = parts[0], parts[1], parts[2], parts[3]
        m = _SCORE.search(feats)
        if not m or float(m.group(1)) < min_score or src == dst:
            continue
        score = round(float(m.group(1)), 3)
        if _SLOT.search(src) or _SLOT.search(dst):
            if sorted(_SLOT.findall(src)) == sorted(_SLOT.findall(dst)) and len(src.split()) <= 6:
                key = (lhs, src, dst)
                patterns[key] = max(score, patterns.get(key, 0))
            continue
        if not (_WORDS.fullmatch(src) and _WORDS.fullmatch(dst)) or not (_safe(src) and _safe(dst)):
            continue
        per = phrases.setdefault(src, {})
        per[dst] = max(score, per.get(dst, 0))
    ranked = {k: sorted(([d, s] for d, s in v.items()), key=lambda x: -x[1])[:8] for k, v in sorted(phrases.items())}
    pats = sorted(([*k, s] for k, s in patterns.items()), key=lambda x: -x[3])
    return ranked, pats


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("inputs", nargs="+", type=Path, help="PPDB 2.0 files (.gz or plain text)")
    p.add_argument("--min-score", type=float, default=3.5, help="keep pairs with PPDB2Score at least this")
    p.add_argument("--out", type=Path, default=OUT)
    args = p.parse_args()

    def all_lines() -> Iterator[str]:
        for path in args.inputs:
            yield from _lines(path)

    phrases, patterns = parse(all_lines(), args.min_score)
    about = "Generated by tools/build_ppdb.py from PPDB 2.0 (CC-BY 3.0, Pavlick et al. 2015). Do not edit."
    args.out.write_text(
        json.dumps({"_about": about, "phrases": phrases, "patterns": patterns}, ensure_ascii=False, indent=0) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {args.out} ({len(phrases)} phrases, {len(patterns)} patterns)")


if __name__ == "__main__":
    main()
