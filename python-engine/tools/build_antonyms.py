"""Build app/data/antonyms.json: opposite-word pairs from WordNet.

Build-time only, with the same dependencies as build_lexicon.py:

    python -m pip install -r python-engine/tools/requirements-build.txt
    python python-engine/tools/build_antonyms.py

The rule engine rejects a synonym that is the opposite of the word it replaces
or of another word in the same sentence, and the editor never suggests one.

WordNet records antonyms between single word senses ("hot" / "cold"). Each
pair is widened to the other words of both senses and, for adjectives, to
their "similar to" satellites, so "scorching" / "freezing" are caught too.
A word only counts with one of its --senses most common senses, so a rare
reading ("strong" as in "strong butter") does not oppose it to "fresh".

Only words the engine can swap in (the hand-written groups in lexicon.py and
synonyms_extra.json) get an entry; the opposite side is any common word.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ENGINE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ENGINE))

from app.core import lexicon as lx  # noqa: E402

OUT = ENGINE / "app" / "data" / "antonyms.json"


def vocabulary() -> set[str]:
    """Every single word the engine may swap in or suggest."""
    words: set[str] = set()
    for word, (_pos, alts) in lx.SYNONYMS.items():
        words.add(word)
        words.update(alts)
    for word, (_pos, alts) in lx.EXTRA_SYNONYMS.items():
        words.add(word)
        words.update(alts)
    return {w for w in words if w.isalpha()}


def _sense_words(synset, top: set) -> set[str]:
    """Words of ``synset`` and its satellites, keeping only words for which it is a common sense."""
    synsets = [synset]
    if synset.pos() in ("a", "s"):
        synsets += synset.similar_tos()
    return {lemma.name().lower() for s in synsets for lemma in s.lemmas() if (lemma.name().lower(), s) in top}


def build(min_zipf: float, senses: int) -> dict[str, list[str]]:
    from nltk.corpus import wordnet as wn
    from wordfreq import zipf_frequency

    vocab = vocabulary()
    common: dict[str, bool] = {}

    def is_common(w: str) -> bool:
        if w not in common:
            common[w] = w.isalpha() and zipf_frequency(w, "en") >= min_zipf
        return common[w]

    # (word, synset) pairs where the synset is one of the word's most common senses
    top = {
        (lemma.name().lower(), lemma.synset())
        for synset in wn.all_synsets()
        for lemma in synset.lemmas()
        if lemma.synset() in wn.synsets(lemma.name())[:senses]
    }

    out: dict[str, set[str]] = {}
    for synset in wn.all_synsets():
        for lemma in synset.lemmas():
            for anto in lemma.antonyms():
                left, right = _sense_words(synset, top), _sense_words(anto.synset(), top)
                for a in left:
                    for b in right:
                        if a == b or not (is_common(a) and is_common(b)):
                            continue
                        if a in vocab:
                            out.setdefault(a, set()).add(b)
                        if b in vocab:
                            out.setdefault(b, set()).add(a)
    return {w: sorted(opp) for w, opp in sorted(out.items())}


def dump(payload: dict) -> str:
    """JSON with one word per line, so regenerating gives a readable diff."""
    about = payload.pop("_about")
    lines = ["{", f' "_about": {json.dumps(about)},']
    items = list(payload.items())
    for i, (word, opp) in enumerate(items):
        lines.append(f"  {json.dumps(word)}: {json.dumps(opp)}" + ("," if i < len(items) - 1 else ""))
    return "\n".join(lines + ["}", ""])


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--min-zipf", type=float, default=2.5, help="skip words rarer than this (wordfreq Zipf)")
    p.add_argument("--senses", type=int, default=3, help="how many of a word's senses count")
    p.add_argument("--out", type=Path, default=OUT)
    args = p.parse_args()

    import nltk

    nltk.download("wordnet", quiet=True)

    data = build(args.min_zipf, args.senses)
    payload = {
        "_about": "Generated by tools/build_antonyms.py from WordNet 3.0 and wordfreq. Do not edit; "
        "maps each word the engine can swap in to its opposites.",
        **data,
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(dump(payload), encoding="utf-8")
    print(f"Wrote {args.out} ({len(data)} words, {sum(map(len, data.values()))} opposites)")


if __name__ == "__main__":
    main()
