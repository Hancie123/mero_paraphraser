"""Build app/data/word_freq.json: how common each swappable word is, from wordfreq.

Build-time only:

    python -m pip install -r python-engine/tools/requirements-build.txt
    python python-engine/tools/build_freq.py

Values are Zipf frequencies (log10 of uses per billion words, about 1-7:
"people" 6.6, "tired" 4.9, "weary" 3.6). The rule engine skips a synonym that is
much rarer than the word it replaces (rule_engine.RARE_GAP), so general text
does not pick up words like "weary" or "educator" for "tired" or "teacher".

Every word and phrase in the hand-written groups (lexicon.GROUPS) gets an
entry, in its base and -s forms, since those are the ones the engine swaps in.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from wordfreq import zipf_frequency

ENGINE = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ENGINE))

from app.core import lexicon as lx  # noqa: E402

OUT = ENGINE / "app" / "data" / "word_freq.json"


def main() -> None:
    words: set[str] = set()
    for pos, group, _keys in lx.GROUPS:
        for w in group:
            words.add(w)
            if pos in (lx.N, lx.V):
                words.add(lx.pluralize(w, pos))
    freq = {w: round(zipf_frequency(w, "en"), 2) for w in sorted(words)}
    data = {"_about": "Generated by tools/build_freq.py from wordfreq (Zipf scale). Do not edit.", "zipf": freq}
    OUT.write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8")
    print(f"{len(freq)} words -> {OUT}")


if __name__ == "__main__":
    main()
